    /**
     * Longest-match country code from digit string (no + / access prefix).
     */
    public static function match(string $digits): ?string
    {
        $digits = preg_replace('/\D+/', '', $digits) ?? '';
        if ($digits === '') {
            return null;
        }
        foreach (self::all() as $cc) {
            if (str_starts_with($digits, $cc)) {
                return $cc;
            }
        }

        return null;
    }
